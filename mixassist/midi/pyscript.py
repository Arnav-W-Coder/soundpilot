"""ADR-2 piano roll write path: generate MCP_Apply.pyscript with the notes baked in.

Template after [RS-NB] pyscript_gen.py. FL's pyscript sandbox blocks file I/O, so the notes
are a Python literal; the script converts beats to ticks with the live flp.score.PPQ.
Re-running it (Ctrl+Alt+Y) re-reads the file: PROBE P7.
"""
from __future__ import annotations

import os

from mixassist.fl.paths import find_fl_subdir
from mixassist.errors import ToolError
from mixassist.midi.io import Note

APPLY_SCRIPT_NAME = "MCP_Apply.pyscript"
PYSCRIPT_DIR_ENV = "SOUNDPILOT_PYSCRIPT_DIR"

USER_ACTION = (
    "In FL: open this channel's piano roll → Scripting → MCP Apply "
    "(first time this session), afterwards press Ctrl+Alt+Y."
)

_TEMPLATE = '''# Script.Name = "MCP Apply"
# Script.Category = "MCP"
# Generated by MixAssist from {source}. Overwritten on every fix_midi; do not edit.

import flpianoroll as flp

# (pitch, start_beats, length_beats, velocity 0..1)
NOTES = {notes}


def _run():
    score = flp.score
    ppq = score.PPQ
    try:
        score.clearNotes(True)
    except TypeError:
        score.clearNotes()
    for pitch, start, length, vel in NOTES:
        n = flp.Note()
        n.number = int(pitch)
        n.time = int(round(start * ppq))
        n.length = max(1, int(round(length * ppq)))
        n.velocity = float(vel)
        score.addNote(n)


def _go():
    undo = getattr(flp.score, "undoSection", None)
    if callable(undo):
        try:
            with undo():
                _run()
            return
        except Exception:
            pass
    _run()


_go()
'''


def default_script_dir() -> str | None:
    """FL's "Settings/Piano roll scripts" folder, or None if it doesn't exist."""
    override = os.environ.get(PYSCRIPT_DIR_ENV)
    if override:
        return os.path.expanduser(override)
    found = find_fl_subdir("Piano roll scripts")
    return str(found) if found else None


def render(notes: list[Note], source: str = "") -> str:
    rows = [
        (int(n.pitch), round(float(n.start), 6), round(float(n.length), 6), round(n.velocity / 127.0, 6))
        for n in notes
    ]
    body = "[\n" + "".join(f"    {r!r},\n" for r in rows) + "]"
    src = os.path.basename(source).encode("ascii", "replace").decode("ascii") or "notes"
    return _TEMPLATE.format(source=src, notes=body)


def write(notes: list[Note], source: str = "", fallback_dir: str | None = None) -> str:
    """Write MCP_Apply.pyscript to the FL scripts folder (or fallback_dir) and return its path."""
    d = default_script_dir() or fallback_dir
    if not d:
        raise ToolError("FILE_ERROR", "FL's 'Piano roll scripts' folder was not found",
                        hint=f"set {PYSCRIPT_DIR_ENV} to FL's Settings/Piano roll scripts folder")
    path = os.path.join(d, APPLY_SCRIPT_NAME)
    try:
        os.makedirs(d, exist_ok=True)
        with open(path, "w", encoding="ascii") as f:
            f.write(render(notes, source))
    except OSError as exc:
        raise ToolError("FILE_ERROR", f"cannot write {path}: {exc}") from exc
    return path
